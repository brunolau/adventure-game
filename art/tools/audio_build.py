def synth_doorbell_two_tone() -> list[np.ndarray]:
    """S05: an old mechanical two-tone gate bell (ding-dong, slightly detuned struck bars)."""
    takes = []
    for detune in (1.0, 0.985):
        hi = bell(659.25 * detune, 2.2, decay=0.9) + 0.3 * bell(661.0 * detune, 2.2, decay=0.9)
        lo = bell(523.25 * detune, 2.6, decay=1.1) + 0.3 * bell(524.8 * detune, 2.6, decay=1.1)
        m = np.zeros(int(3.4 * SR))
        m[: len(hi)] += hi
        s = int(0.55 * SR)
        m[s:s + len(lo)] += lo[: len(m) - s]
        takes.append(stereo(m * 0.4))
    return takes


