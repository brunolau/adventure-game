def build_ambience() -> None:
    beds_dir = ASSETS / "ambience" / "beds"
    spots_dir = ASSETS / "ambience" / "spots"
    library: dict[str, dict] = {}
    used_beds = {layer[0] for layers in ROOMS.values() for layer in layers if len(layer) == 2 or layer[2] is None}
    used_spots = {layer[0] for layers in ROOMS.values() for layer in layers if len(layer) > 2 and layer[2] is not None}
    beds = lib_beds()
    for bid, audio in beds.items():
        if bid not in used_beds:
            continue
        loop = audio if bid in SEAMLESS else make_loop(audio, 2.5)
        loop = norm(loop, BED_LUFS)
        dest = beds_dir / f"{bid}.ogg"
        A.encode_ogg(dest, loop, quality=3.0)
        library[bid] = {"kind": "loop", "files": [f"ambience/beds/{bid}.ogg"], "seconds": round(len(loop) / SR, 2)}
        print(f"bed  {bid:20s} {len(loop) / SR:6.1f}s")
    spots = lib_spots()
    for sid, takes in spots.items():
        if sid not in used_spots:
            continue
        files = []
        for k, take in enumerate(takes):
            take = norm(to_mono(take), SPOT_LUFS)
            dest = spots_dir / f"{sid}_{k + 1}.ogg"
            A.encode_ogg(dest, take[:, :1].copy(), quality=4.0)
            files.append(f"ambience/spots/{sid}_{k + 1}.ogg")
        library[sid] = {"kind": "spot", "files": files}
        print(f"spot {sid:20s} {len(files)} takes")
    missing = (used_beds | used_spots) - set(library)
    if missing:
        raise SystemExit(f"layers use unknown sounds: {sorted(missing)}")
    rooms = {}
    for room, layers in ROOMS.items():
        out = []
        for layer in layers:
            entry = {"sound": layer[0], "db": layer[1]}
            if len(layer) > 2 and layer[2] is not None:
                entry["every"] = layer[2]
            if len(layer) > 3:
                entry.update(layer[3])
            out.append(entry)
        rooms[room] = {"layers": out}
    DATA.mkdir(parents=True, exist_ok=True)
    (DATA / "ambience.json").write_text(json.dumps({
        "note": "Room ambience (rooms[].ambience of game.json realised as layers). kind loop = seamless bed, "
                "spot = one-shot takes fired every [min,max] s from a random x (canvas px). db is relative to the "
                "normalised file (beds -24 LUFS, spots -22 LUFS). after/until: action ids. Built by art/tools/audio_build.py.",
        "library": library, "rooms": rooms}, ensure_ascii=False, indent=1), encoding="utf-8")


