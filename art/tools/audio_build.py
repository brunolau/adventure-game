def build_sfx() -> None:
    sfx_dir = ASSETS / "sfx"
    sounds = {}
    for sid, (sources, db, pitch, cooldown, lufs) in SFX.items():
        files = []
        for k, src in enumerate(sources):
            ref, _, take = src.partition("#")
            audio = load(ref, "sfx:" + sid)
            if take:
                audio = splits(audio, 4, max_len=2.0)[int(take)]
            if ref.startswith("fs:326091"):
                audio = fade(audio[: int(3.6 * SR)], 0.01, 0.8)
            # trim leading silence, short fades
            mono = np.abs(audio).max(axis=1)
            lead = int(np.argmax(mono > 10 ** (-50 / 20)))
            audio = fade(audio[lead:], 0.002, min(0.03, len(audio) / SR / 5))
            if len(audio) < int(0.4 * SR):  # ebur128 needs 400 ms: measure with padding
                padded = np.concatenate([audio, np.zeros((int(0.4 * SR), 2), np.float32)])
                lufs_now, _ = A.loudness(padded)
                audio = audio * 10 ** ((lufs - lufs_now) / 20)
                if np.abs(audio).max() > 0.89:
                    audio = audio * (0.89 / np.abs(audio).max())
            else:
                audio = norm(audio, lufs)
            dest = sfx_dir / f"{sid}_{k + 1}.ogg"
            A.encode_ogg(dest, audio, quality=5.0)
            files.append(f"sfx/{sid}_{k + 1}.ogg")
        sounds[sid] = {"files": files, "db": db, "pitch": pitch, "cooldown": cooldown}
        print(f"sfx {sid:16s} {len(files)} file(s)")
    DATA.mkdir(parents=True, exist_ok=True)
    (DATA / "sfx.json").write_text(json.dumps({
        "note": "Sound effects: ids used by game.json actions[].sfx (item_soft, paper, tool_click, soft_success) and "
                "UI/game events (events: event name -> sound id, raised by scripts/Audio/AudioService.cs). Files are "
                "loudness-matched; db/pitch/cooldown are applied at play time. Built by art/tools/audio_build.py.",
        "sounds": sounds, "events": EVENTS}, ensure_ascii=False, indent=1), encoding="utf-8")


